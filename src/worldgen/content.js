// Слухи строятся из настоящих фактов мира (план): ссылаются на реально сгенерированные места.
export function rumorLines(rng, facts) {
  const out = [];
  for (const f of rng.shuffle(facts).slice(0, 3)) {
    const r = f.ref;
    switch (f.kind) {
      case 'cache': out.push(`Говорят, в подвале ${r.gen} кто-то припрятал сундук. Просто так его не открыть.`); break;
      case 'trap': out.push(`Будьте осторожны ${r.loc}: на полу там есть плиты с подвохом. Один бродяга оттуда хромает до сих пор.`); break;
      case 'lock': out.push(`Одна из комнат ${r.gen} заперта на хороший замок. Ключ от неё, говорят, спрятан где-то неподалёку.`); break;
      case 'dungeon': out.push(`За городом, у дороги, есть ${r.nom}. Оттуда по ночам доносится гул, и местные туда не ходят.`); break;
      case 'fortress': out.push(`Говорят, ${r.loc} давно нет хозяина, но стража там всё ещё стоит.`); break;
      case 'tavern': out.push(`Лучший эль в округе наливают ${r.loc}. Спросите хозяина про старые бочки в подвале.`); break;
      default:
    }
  }
  return out;
}
