// Содержимое контейнера. depth 0..3 увеличивает золото; тема определяет вещи.
export function rollLoot(rng, theme, depth = 0) {
  const t = THEME[theme] || THEME.storage, gold = rng.int(t.gold[0], t.gold[1] + depth * 6);
  const loot = { gold, potions: rng.chance((t.potions ?? .22) + depth * .08) ? 1 : 0, torches: rng.chance(.12) ? 1 : 0, gear: [] };
  if (rng.chance(.55 + depth * .1)) loot.gear.push(rng.weighted(t.gear));
  if (depth >= 2 && rng.chance(.35)) loot.gear.push(rng.weighted(THEME.vault.gear));
  return loot;
}
const gearName = g => g.startsWith('Ключ: ') ? `ключ «${g.slice(6)}»` : g.charAt(0).toLowerCase() + g.slice(1);
export const lootSentence = l => {
  const parts = [];
  if (l.gold) parts.push(`${l.gold} ${plural(l.gold, ['монета', 'монеты', 'монет'])}`);
  if (l.potions) parts.push(l.potions === 1 ? 'лечебное зелье' : `${l.potions} ${plural(l.potions, ['лечебное зелье', 'лечебных зелья', 'лечебных зелий'])}`);
  if (l.torches) parts.push(l.torches === 1 ? 'факел' : `${l.torches} ${plural(l.torches, ['факел', 'факела', 'факелов'])}`);
  parts.push(...l.gear.map(gearName));
  return parts.length ? `Внутри: ${parts.join(', ')}.` : 'Внутри только пыль и паутина.';
};
export const lootText = l => lootSentence(l).replace(/^Внутри:? ?/, '').replace(/\.$/, '');

