export function talkFor(rng, building, owner, facts, extraTopic) {
  const kind = GREET[building] ? building : 'house', lines = [rng.pick(GREET[kind])];
  // не более одного слуха каждого вида, не более двух слухов на жителя
  const byKind = new Map(); for (const f of rng.shuffle(facts)) if (!byKind.has(f.kind)) byKind.set(f.kind, f);
  const rumors = rumorLines(rng, [...byKind.values()]).slice(0, 2);
  const topic = TOPICS[building] || TOPICS.house;
  lines.push(rng.pick(topic)); lines.push(...rumors);
  if (extraTopic) lines.push(extraTopic);
  lines.push(rng.pick(BYE)); return { lines, knows: rumors }; // knows — что житель знает о мире (для ИИ-мастера)
}
