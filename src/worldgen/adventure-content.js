export function storyContent(id, settlement, people, tutorial) {
  const template = STORIES[id];
  if (!template) throw new Error('Неизвестная история ' + id);
  return {
    id, ...template, title: `${template.title} · ${settlement}`,
    rescue: `${people.healer.full} перевязывает раны и приводит вас в сознание. «Вы в безопасности на опушке. Следите за здоровьем, пользуйтесь защитой и не забывайте про зелья».`,
    clueProp: 'story-clue', messenger: people.messenger, healer: people.healer, elder: people.elder,
    reportRequires: { clues: ['story-clue'], cleared: ['road-threat'] }, tutorial,
  };
}
