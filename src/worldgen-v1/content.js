// Содержимое контейнера. depth 0..3 увеличивает золото; тема определяет вещи.
export function rollLoot(rng, theme, depth = 0) {
  const t = THEME[theme] || THEME.storage, gold = rng.int(t.gold[0], t.gold[1] + depth * 6);
  const loot = { gold, potions: rng.chance((t.potions ?? .22) + depth * .08) ? 1 : 0, torches: rng.chance(.12) ? 1 : 0, gear: [] };
  if (rng.chance(.55 + depth * .1)) loot.gear.push(rng.weighted(t.gear));
  if (depth >= 2 && rng.chance(.35)) loot.gear.push(rng.weighted(THEME.vault.gear));
  return loot;
}
