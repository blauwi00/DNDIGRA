export function settlementName(rng) {
  const [g, n] = rng.pick(PLACES), r = rng.next();
  if (r < .45) return `${rng.pick(ADJ)[g]} ${n}`;                                   // «Серая Заводь»
  if (r < .7) { const who = rng.pick(rng.chance(.5) ? MALE : FEMALE); return `${n} ${who[1]}`; } // «Брод Борга»
  if (r < .85) return `${rng.pick(FIRST)[g]} ${n}`;                                    // «Новая Заводь»
  return `${rng.pick(ADJ)[g]} ${n} ${rng.pick(SUFFIX)}`;                           // «Каменный Мост у реки»
}
export function tavernName(rng) { return rng.chance(.5) ? `${rng.pick(TAV_AM)} ${rng.pick(TAV_M)}` : `${rng.pick(TAV_AF)} ${rng.pick(TAV_F)}`; }
export function person(rng, gender = rng.pick(['male', 'female'])) {
  const [nom, gen] = rng.pick(gender === 'female' ? FEMALE : MALE), epi = rng.chance(.55) ? ' ' + rng.pick(gender === 'female' ? EPITHET_F : EPITHET) : '';
  return { gender, first: nom, genitive: gen, full: nom + epi };
}

