// Слухи строятся из настоящих фактов мира (план): ссылаются на реально сгенерированные места.
export function rumorLines(rng, facts) {
  const out = [];
  for (const f of rng.shuffle(facts).slice(0, 3)) {
    switch (f.kind) {
      case 'cache': out.push(`Говорят, в подвале «${f.place}» кто-то припрятал сундук. Только вот просто так его не открыть.`); break;
      case 'trap': out.push(`Осторожнее в ${f.where}: там пол с подвохом. Один бродяга оттуда хромает до сих пор.`); break;
      case 'lock': out.push(`${f.where} заперто на хороший замок. Ключ, говорят, лежит где-то в ${f.keyWhere}.`); break;
      case 'dungeon': out.push(`За околицей есть ${f.place}. Оттуда по ночам доносится гул, и местные туда не ходят.`); break;
      case 'fortress': out.push(`${f.place} на холме давно не знало хозяина. Стража там, впрочем, есть, и очень злая.`); break;
      case 'tavern': out.push(`Лучший эль в округе наливают в «${f.place}». Спросите хозяина про старые бочки в подвале.`); break;
      case 'sewer': out.push(`Под ${f.where} проходят старые ходы. Говорят, они тянутся до самого ${f.to}.`); break;
      default:
    }
  }
  return out;
}
export function dialogueFor(rng, building, owner, facts, extraTopic) {
  const kind = GREET[building] ? building : 'house', lines = [rng.pick(GREET[kind])];
  const rumors = rumorLines(rng, facts); lines.push(...rumors);
  if (!rumors.length) lines.push(rng.pick(['Новостей мало. Урожай, погода да дорога, всё как обычно.', 'Живём как живём. Скоро, говорят, будут холода.']));
  if (extraTopic) lines.push(extraTopic);
  lines.push(rng.pick(BYE)); return lines;
}

